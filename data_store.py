def all(table):
    """取整张表（返回的是内存里的行，只读使用）。"""
    return STORE.get(table, [])


def get(table, row_id):
    for row in STORE.get(table, []):
        if row.get("id") == row_id:
            return row
    return None


def where(table, **cond):
    """等值条件筛选：where("posts", user_id=1)。"""
    rows = []
    for row in STORE.get(table, []):
        # 注意：本模块自己定义了 all()，这里必须用内置的 builtins.all
        if builtins.all(row.get(k) == v for k, v in cond.items()):
            rows.append(row)
    return rows


def find(table, pred):
    """自定义条件筛选：find("posts", lambda r: r["likes"] > 10)。"""
    return [row for row in STORE.get(table, []) if pred(row)]


def search(table, keyword, fields):
    """模糊检索（相当于 SQL 的 LIKE %kw%），任一字段包含即命中。"""
    kw = (keyword or "").strip().lower()
    if not kw:
        return list(STORE.get(table, []))
    out = []
    for row in STORE.get(table, []):
        for f in fields:
            v = row.get(f)
            if v and kw in str(v).lower():
                out.append(row)
                break
    return out


def sort_by(rows, field, reverse=True):
    return sorted(rows, key=lambda r: (r.get(field) is None, r.get(field)), reverse=reverse)


def latest(rows, field="created_at", n=None):
    """按时间倒序（时间是 datetime，直接排序即可），可只取前 n 条。"""
    ordered = sorted(rows, key=lambda r: r.get(field) or 0, reverse=True)
    return ordered[:n] if n else ordered


def insert(table, **fields):
    """插入一行：自动分配 id，自动补 created_at，并自动落盘。
    （第一个参数特意叫 table 而不是 name，避免和业务字段 name 撞名）"""
    with _LOCK:
        if table not in STORE:
            STORE[table] = []
        row = dict(fields)
        row["id"] = _NEXT_ID.get(table, 1)
        _NEXT_ID[table] = row["id"] + 1
        if table in _MUTABLE and table != "users" and "created_at" not in row:
            row["created_at"] = datetime.now()
        STORE[table].append(row)
        if table in _MUTABLE:
            save()
        return row


def update(table, row_id, **fields):
    """按 id 修改一行，并自动落盘。"""
    with _LOCK:
        row = get(table, row_id)
        if row is None:
            return None
        row.update(fields)
        if table in _MUTABLE:
            save()
        return row


def incr(table, row_id, field, step=1):
    """数值字段自增（点赞、浏览）。"""
    row = get(table, row_id)
    if row is None:
        return None
    row[field] = (row.get(field) or 0) + step
    if table in _MUTABLE:
        save()
    return row


def count(table, **cond):
    return len(where(table, **cond)) if cond else len(STORE.get(table, []))


