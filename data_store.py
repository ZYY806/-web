# 只有这几张表会落盘（内容表随代码走，不需要存）
_MUTABLE = ("users", "posts", "comments", "sticky_notes", "contact_messages")

_NEXT_ID = {}


def _recalc_ids():
    for name in STORE:
        rows = STORE[name]
        _NEXT_ID[name] = (max([r["id"] for r in rows]) + 1) if rows else 1


def _json_default(obj):
    if isinstance(obj, datetime):
        return obj.isoformat(timespec="seconds")
    raise TypeError(str(type(obj)))


def _row_to_json(row):
    out = {}
    for k, v in row.items():
        out[k] = v.isoformat(timespec="seconds") if isinstance(v, datetime) else v
    return out


def _row_from_json(row):
    out = dict(row)
    for k, v in list(out.items()):
        if k.endswith("_at") and isinstance(v, str) and v:
            try:
                out[k] = datetime.fromisoformat(v)
            except ValueError:
                pass
    return out


def save():
    """把互动内容写进 data/store.json（相当于数据库的一次提交）。"""
    with _LOCK:
        os.makedirs(DATA_DIR, exist_ok=True)
        payload = {"_version": 2, "_saved_at": datetime.now().isoformat(timespec="seconds")}
        for name in _MUTABLE:
            payload[name] = [_row_to_json(r) for r in STORE[name]]
        tmp = STORE_FILE + ".tmp"
        with open(tmp, "w", encoding="utf-8") as f:
            json.dump(payload, f, ensure_ascii=False, indent=1)
        os.replace(tmp, STORE_FILE)


def load():
    """启动时读入互动内容；文件不存在或损坏就用示例数据初始化。"""
    with _LOCK:
        for name in _MUTABLE:
            STORE[name] = []
        loaded = False
        if os.path.exists(STORE_FILE):
            try:
                with open(STORE_FILE, encoding="utf-8") as f:
                    payload = json.load(f)
                for name in _MUTABLE:
                    STORE[name] = [_row_from_json(r) for r in payload.get(name) or []]
                loaded = True
            except Exception as e:
                print(f"[数据] store.json 读取失败，改用内置示例数据：{e}")
                loaded = False
        if not loaded:
            STORE["users"] = [dict(r) for r in USERS_SEED]
            STORE["posts"] = [dict(r) for r in POSTS_SEED]
            STORE["comments"] = [dict(r) for r in COMMENTS_SEED]
            STORE["sticky_notes"] = [dict(r) for r in STICKY_NOTES_SEED]
            STORE["contact_messages"] = [dict(r) for r in CONTACT_MESSAGES_SEED]
        if not STORE["users"]:
            STORE["users"] = [dict(r) for r in USERS_SEED]
        if not STORE["sticky_notes"]:
            STORE["sticky_notes"] = [dict(r) for r in STICKY_NOTES_SEED]
        _recalc_ids()
        if not loaded:
            save()
        return loaded


